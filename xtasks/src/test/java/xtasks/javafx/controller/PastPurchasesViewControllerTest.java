    @Test
    public void testimporting() throws Exception {
        xtasks.backend.services.PurchaseImportService importer = mock(xtasks.backend.services.PurchaseImportService.class);
        javafx.scene.text.Text status = mock(javafx.scene.text.Text.class);
        org.springframework.test.util.ReflectionTestUtils.setField(ppcontroller, "importService", importer);
        org.springframework.test.util.ReflectionTestUtils.setField(ppcontroller, "delete", status);
        File file = new File("purchases.csv");
        when(purchaseService.P_items()).thenReturn(Collections.emptyList());
        when(importer.importCsv(file)).thenReturn(true, false);
        ppcontroller.saveImports(file);
        verify(status).setText("CSV imported successfully.");
        ppcontroller.saveImports(file);
        verify(status).setText("Skipped: this file content has already been imported.");
        File unsupported = new File("purchases.json");
        when(importer.importCsv(unsupported)).thenThrow(new IllegalArgumentException("Only CSV files are supported."));
        ppcontroller.saveImports(unsupported);
        verify(status).setText("Import failed: Only CSV files are supported.");
    }

